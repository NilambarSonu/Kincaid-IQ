// ─── Helpers ─────────────────────────────────────────────────────────────────

function fmtDate(iso: string): string {
  try {
    return new Date(iso).toLocaleString("en-US", {
      month: "short", day: "numeric", year: "numeric",
      hour: "numeric", minute: "2-digit",
    });
  } catch {
    return iso;
  }
}

function ScoreDelta({ a, b }: { a: number | null; b: number | null }) {
  if (a === null || b === null) return null;
  const delta = b - a;
  const abs = Math.abs(delta).toFixed(1);
  if (delta > 0.4)
    return <span className="flex items-center gap-0.5 text-emerald-400 font-black text-xs"><TrendingUp className="w-3 h-3" />+{abs}</span>;
  if (delta < -0.4)
    return <span className="flex items-center gap-0.5 text-red-400 font-black text-xs"><TrendingDown className="w-3 h-3" />-{abs}</span>;
  return <span className="flex items-center gap-0.5 text-zinc-500 text-xs"><Minus className="w-3 h-3" />≈</span>;
}

// ─── Single-entry PDF export ─────────────────────────────────────────────────

function downloadEntryPdf(entry: HistoryEntry): void {
  const doc = new jsPDF({ unit: "mm", format: "letter" });
  const W = doc.internal.pageSize.getWidth();
  const H = doc.internal.pageSize.getHeight();
  const M = 16;
  const CW = W - M * 2;

  const BG: [number, number, number] = [3, 5, 13];
  const BG2: [number, number, number] = [8, 11, 24];
  const BG3: [number, number, number] = [14, 18, 38];
  const FG: [number, number, number] = [210, 220, 242];
  const FG2: [number, number, number] = [135, 153, 195];
  const FG3: [number, number, number] = [65, 80, 120];
  const SEP: [number, number, number] = [24, 32, 68];
  const GOLD: [number, number, number] = [255, 184, 0];
  const ACCENT: [number, number, number] = [191, 95, 255];

  const setFill = (c: [number, number, number]) => doc.setFillColor(c[0], c[1], c[2]);
  const setText = (c: [number, number, number]) => doc.setTextColor(c[0], c[1], c[2]);
  const setStroke = (c: [number, number, number]) => doc.setDrawColor(c[0], c[1], c[2]);

  let page = 1;
  let y = 0;

  const drawChrome = () => {
    setFill(BG);
    doc.rect(0, 0, W, H, "F");
    setFill(BG2);
    doc.rect(0, 0, W, 14, "F");
    setFill(ACCENT);
    doc.rect(0, 14, W, 0.6, "F");
    doc.setFont("helvetica", "bold");
    doc.setFontSize(8);
    setText(GOLD);
    doc.text("KINCAID IQ", M, 9);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(7.5);
    setText(FG2);
    doc.text("EXECUTIVE SUMMARY", M + 24, 9);
    setText(FG3);
    doc.text(
      new Date().toLocaleDateString("en-US", { month: "short", day: "numeric", year: "numeric" }),
      W - M, 9, { align: "right" }
    );
    setFill(BG2);
    doc.rect(0, H - 11, W, 11, "F");
    setFill(ACCENT);
    doc.rect(0, H - 11, W, 0.4, "F");
    doc.setFont("helvetica", "normal");
    doc.setFontSize(7);
    setText(FG3);
    doc.text("Generated by Kincaid IQ · Fiduciary intelligence platform", M, H - 5);
    doc.text(`Page ${page}`, W - M, H - 5, { align: "right" });
  };

  const ensureSpace = (needed: number) => {
    if (y + needed > H - 16) {
      doc.addPage();
      page += 1;
      drawChrome();
      y = 22;
    }
  };

  const sectionLabel = (label: string) => {
    ensureSpace(10);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(8);
    setText(GOLD);
    doc.text(label.toUpperCase(), M, y);
    setStroke(SEP);
    doc.setLineWidth(0.2);
    doc.line(M, y + 1.5, W - M, y + 1.5);
    y += 6;
  };

  const renderParagraph = (text: string, lineHeight = 4.6, fontSize = 9.5) => {
    doc.setFont("helvetica", "normal");
    doc.setFontSize(fontSize);
    setText(FG);
    const lines = doc.splitTextToSize(text, CW) as string[];
    for (const line of lines) {
      ensureSpace(lineHeight + 1);
      doc.text(line, M, y);
      y += lineHeight;
    }
    y += 2;
  };

  drawChrome();
  y = 24;

  const label = entry.label || fmtDate(entry.generated_at);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(18);
  setText(FG);
  doc.text("Executive Summary", M, y);
  y += 7;

  doc.setFont("helvetica", "normal");
  doc.setFontSize(9.5);
  setText(FG2);
  doc.text("Single-version analysis · Kincaid IQ analysis history", M, y);
  y += 9;

  setFill(BG3);
  doc.roundedRect(M, y, CW, 22, 2, 2, "F");
  doc.setFont("helvetica", "bold");
  doc.setFontSize(7.5);
  setText(FG3);
  doc.text("VERSION", M + 4, y + 5);
  doc.text("GENERATED", M + CW / 2 + 4, y + 5);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(10.5);
  setText(FG);
  doc.text(doc.splitTextToSize(label, CW / 2 - 8)[0] ?? label, M + 4, y + 11);
  doc.text(
    doc.splitTextToSize(fmtDate(entry.generated_at), CW / 2 - 8)[0] ?? fmtDate(entry.generated_at),
    M + CW / 2 + 4, y + 11
  );
  doc.setFont("helvetica", "normal");
  doc.setFontSize(8);
  setText(FG2);
  const score = entry.score_snapshot;
  doc.text(score !== null ? `Score: ${score.toFixed(1)} / 100` : "Score: —", M + 4, y + 18);
  doc.text(`Entity: ${entry.entity_id}`, M + CW / 2 + 4, y + 18);
  y += 28;

  const headline = (entry.output_json.headline as string | undefined) ?? null;
  const action = (entry.output_json.action as string | undefined) ?? null;
  const paragraphs = (entry.output_json.paragraphs as string[] | undefined) ?? [];

  if (headline) {
    sectionLabel("Headline");
    doc.setFont("helvetica", "bold");
    doc.setFontSize(11);
    setText(FG);
    const lines = doc.splitTextToSize(headline, CW) as string[];
    for (const line of lines) {
      ensureSpace(6);
      doc.text(line, M, y);
      y += 5;
    }
    y += 3;
  }

  if (paragraphs.length > 0) {
    sectionLabel("Analysis");
    paragraphs.forEach((p, i) => {
      ensureSpace(8);
      doc.setFont("helvetica", "bold");
      doc.setFontSize(8);
      setText(FG2);
      doc.text(`¶${i + 1}`, M, y);
      y += 4.5;
      renderParagraph(p);
    });
  }

  if (action) {
    sectionLabel("Recommended Next Step");
    renderParagraph(action, 4.8, 10);
  }

  if (entry.tool === "benchmarking") {
    const pct = (entry.output_json.percentiles as Record<string, number | null> | undefined) ?? null;
    const pmpm = (entry.output_json.employerPmpm as number | null | undefined) ?? null;
    const year = (entry.output_json.year as number | undefined) ?? null;
    if (pct || pmpm != null) {
      sectionLabel(`Percentile Positioning${year ? ` (${year})` : ""}`);
      const rowH = 6.2;
      const colValW = 30;
      const colLabelW = CW - colValW;
      const xLabel = M;
      const xVal = M + colLabelW;

      ensureSpace(rowH + 2);
      setFill(BG3);
      doc.rect(M, y - 4, CW, rowH, "F");
      doc.setFont("helvetica", "bold");
      doc.setFontSize(7);
      setText(FG3);
      doc.text("METRIC", xLabel + 2, y);
      doc.text("VALUE", xVal + colValW - 2, y, { align: "right" });
      y += rowH;

      const labelMap: Record<string, string> = {
        adminFees: "Admin Fees",
        brokerCommissions: "Broker Commissions",
        totalIncome: "Plan Income",
      };
      (["adminFees", "brokerCommissions", "totalIncome"] as const).forEach(k => {
        ensureSpace(rowH + 1);
        doc.setFont("helvetica", "normal");
        doc.setFontSize(9);
        setText(FG);
        doc.text(labelMap[k], xLabel + 2, y);
        const v = pct?.[k] ?? null;
        setText(FG2);
        doc.text(v == null ? "—" : `${v}th`, xVal + colValW - 2, y, { align: "right" });
        y += rowH;
        setStroke(SEP);
        doc.setLineWidth(0.1);
        doc.line(M, y - rowH + 1.6, M + CW, y - rowH + 1.6);
      });

      ensureSpace(rowH + 2);
      setStroke(SEP);
      doc.setLineWidth(0.3);
      doc.line(M, y - 1, M + CW, y - 1);
      y += 1;
      doc.setFont("helvetica", "bold");
      doc.setFontSize(9);
      setText(FG);
      doc.text("PMPM", xLabel + 2, y);
      setText(FG2);
      doc.text(pmpm != null ? `$${pmpm}` : "—", xVal + colValW - 2, y, { align: "right" });
      y += rowH + 2;
    }
  }

  const safeEntity = (entry.entity_id || "entry").replace(/[^a-z0-9_-]/gi, "_").slice(0, 40);
  const safeLabel = (entry.label
    ? entry.label.replace(/[^a-z0-9_-]/gi, "_").slice(0, 40)
    : entry.generated_at.slice(0, 10)
  );
  doc.save(`kincaid-iq-analysis-${safeEntity}-${safeLabel}.pdf`);
}

