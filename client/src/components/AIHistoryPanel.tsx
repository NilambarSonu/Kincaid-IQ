  // Word-level diff via LCS. Splits on whitespace boundaries while preserving
  // the whitespace as its own token so reconstruction is faithful.
  function tokenize(s: string): string[] {
    return s.split(/(\s+)/).filter(t => t.length > 0);
  }

  type DiffOp = { type: "eq" | "add" | "del"; text: string };

  function wordDiff(a: string, b: string): { left: DiffOp[]; right: DiffOp[] } {
    const ta = tokenize(a);
    const tb = tokenize(b);
    const n = ta.length, m = tb.length;
    // LCS table
    const dp: number[][] = Array.from({ length: n + 1 }, () => new Array(m + 1).fill(0));
    for (let i = n - 1; i >= 0; i--) {
      for (let j = m - 1; j >= 0; j--) {
        dp[i][j] = ta[i] === tb[j] ? dp[i + 1][j + 1] + 1 : Math.max(dp[i + 1][j], dp[i][j + 1]);
      }
    }
    const left: DiffOp[] = [];
    const right: DiffOp[] = [];
    let i = 0, j = 0;
    while (i < n && j < m) {
      if (ta[i] === tb[j]) {
        left.push({ type: "eq", text: ta[i] });
        right.push({ type: "eq", text: tb[j] });
        i++; j++;
      } else if (dp[i + 1][j] >= dp[i][j + 1]) {
        left.push({ type: "del", text: ta[i] });
        i++;
      } else {
        right.push({ type: "add", text: tb[j] });
        j++;
      }
    }
    while (i < n) { left.push({ type: "del", text: ta[i++] }); }
    while (j < m) { right.push({ type: "add", text: tb[j++] }); }
    return { left, right };
  }

  function DiffText({ ops, side }: { ops: DiffOp[]; side: "left" | "right" }) {
    return (
      <p className="text-xs leading-relaxed text-zinc-300">
        {ops.map((op, idx) => {
          if (op.type === "eq") {
            return <span key={idx} className="text-zinc-500">{op.text}</span>;
          }
          if (side === "left" && op.type === "del") {
            return (
              <span
                key={idx}
                className="rounded px-0.5 line-through"
                style={{ background: "rgba(255,77,109,0.18)", color: "#FF8FA3" }}
                data-testid="diff-removed"
              >
                {op.text}
              </span>
            );
          }
          if (side === "right" && op.type === "add") {
            return (
              <span
                key={idx}
                className="rounded px-0.5"
                style={{ background: "rgba(0,255,148,0.15)", color: "#5EE8B0" }}
                data-testid="diff-added"
              >
                {op.text}
              </span>
            );
          }
          return null;
        })}
      </p>
    );
  }

  function DiffBlock({ labelLeft, labelRight, left, right, highlight }: {
    labelLeft: string; labelRight: string;
    left: string | null; right: string | null;
    highlight?: boolean;
  }) {
    const isDiff = left !== right;
    if (changesOnly && !isDiff) return null;
    const bothPresent = left !== null && right !== null;
    const diff = bothPresent && isDiff ? wordDiff(left, right) : null;
    return (
      <div className={`grid grid-cols-2 gap-3 rounded-xl p-4 ${highlight ? "border" : ""}`}
        style={highlight ? { background: "rgba(255,184,0,0.04)", borderColor: "rgba(255,184,0,0.15)" } : {}}>
        <div>
          <div className="text-[9px] font-mono text-zinc-600 uppercase tracking-widest mb-1.5">{labelLeft}</div>
          {diff
            ? <DiffText ops={diff.left} side="left" />
            : <p className="text-xs text-zinc-400 leading-relaxed">{left ?? "—"}</p>}
        </div>
        <div>
          <div className="text-[9px] font-mono text-zinc-600 uppercase tracking-widest mb-1.5 flex items-center gap-1.5">
            {labelRight}
            {isDiff && <span className="w-1.5 h-1.5 rounded-full bg-amber-400 inline-block" />}
          </div>
          {diff
            ? <DiffText ops={diff.right} side="right" />
            : <p className={`text-xs leading-relaxed ${isDiff ? "text-white font-medium" : "text-zinc-400"}`}>{right ?? "—"}</p>}
        </div>
      </div>
    );
  }

