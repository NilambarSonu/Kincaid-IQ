import { useState } from "react";
import { Download, FileText } from "lucide-react";
import { clientProfile } from "@/lib/mockData";

export function ExportButton() {
  const [exporting, setExporting] = useState(false);

  const handleExport = async () => {
    setExporting(true);
    try {
      const jspdf = await import("jspdf");
      const html2canvas = await import("html2canvas");
      const jsPDF = jspdf.default || (jspdf as any).jsPDF;

      const main = document.querySelector("main") || document.body;
      const canvas = await html2canvas.default(main as HTMLElement, {
        backgroundColor: "#020214",
        scale: 1.5,
        useCORS: true,
        logging: false,
        windowWidth: 1280,
      });

      const imgData = canvas.toDataURL("image/jpeg", 0.92);
      const pdf = new jsPDF({ orientation: "landscape", unit: "mm", format: "a4" });
      const pdfW = pdf.internal.pageSize.getWidth();
      const pdfH = pdf.internal.pageSize.getHeight();

      pdf.setFillColor(2, 2, 20);
      pdf.rect(0, 0, pdfW, pdfH, "F");

      const headerH = 14;
      pdf.setFillColor(8, 10, 40);
      pdf.rect(0, 0, pdfW, headerH, "F");

      pdf.setFont("helvetica", "bold");
      pdf.setFontSize(11);
      pdf.setTextColor(255, 184, 0);
      pdf.text("KINCAID IQ", 10, 9);

      pdf.setFont("helvetica", "normal");
      pdf.setFontSize(8);
      pdf.setTextColor(130, 150, 200);
      pdf.text(`${clientProfile.name} • ${clientProfile.brokerage}`, 42, 9);

      pdf.setTextColor(100, 120, 160);
      const dateStr = new Date().toLocaleDateString("en-US", { month: "long", day: "numeric", year: "numeric" });
      pdf.text(dateStr, pdfW - 10, 9, { align: "right" });

      pdf.setDrawColor(0, 140, 255);
      pdf.setLineWidth(0.2);
      pdf.line(0, headerH, pdfW, headerH);

      const imgRatio = canvas.width / canvas.height;
      const availH = pdfH - headerH - 6;
      const availW = pdfW - 16;
      let imgW = availW;
      let imgH = availW / imgRatio;
      if (imgH > availH) {
        imgH = availH;
        imgW = availH * imgRatio;
      }
      const imgX = (pdfW - imgW) / 2;
      pdf.addImage(imgData, "JPEG", imgX, headerH + 4, imgW, imgH);

      const footerY = pdfH - 3;
      pdf.setFontSize(6);
      pdf.setTextColor(60, 80, 110);
      pdf.text("CONFIDENTIAL — For authorized use only. Generated by Kincaid IQ / Kincaid RMC.", pdfW / 2, footerY, { align: "center" });

      const pageName = window.location.pathname.replace("/", "") || "dashboard";
      pdf.save(`kincaid-iq-${pageName}-${Date.now()}.pdf`);
    } catch (err) {
      console.error("Export failed:", err);
    } finally {
      setExporting(false);
    }
  };

  return (
    <button
      onClick={handleExport}
      disabled={exporting}
      className="fixed bottom-6 right-6 z-40 flex items-center gap-2 px-4 py-2.5 rounded-xl font-semibold text-xs transition-all duration-200"
      style={{
        background: exporting ? "rgba(0,140,255,0.15)" : "rgba(0,140,255,0.12)",
        border: "1px solid rgba(0,140,255,0.3)",
        color: exporting ? "rgba(0,168,255,0.5)" : "rgba(0,168,255,0.85)",
        boxShadow: "0 0 20px rgba(0,140,255,0.12), 0 4px 16px rgba(0,0,0,0.4)",
        backdropFilter: "blur(12px)",
        cursor: exporting ? "wait" : "pointer",
      }}
      data-testid="button-export-pdf"
    >
      {exporting ? (
        <>
          <FileText size={13} className="animate-pulse" />
          Generating…
        </>
      ) : (
        <>
          <Download size={13} />
          Export PDF
        </>
      )}
    </button>
  );
}
